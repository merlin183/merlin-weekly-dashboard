"""Build the readable CS page using only the Python standard library.

Run ``python scripts/build_cs_app.py`` after editing ``src/cs_app.src.html``.
Run with ``--check`` to verify that the checked-in artifact matches its source.
The generated source hash makes provenance easy to inspect. No external tools,
network access, or temporary files are needed.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "cs_app.src.html"
OUT = ROOT / "src" / "cs_app.html"


def render(source: str) -> str:
    source = source.replace("\r\n", "\n").replace("\r", "\n")
    digest = hashlib.sha256(source.encode("utf-8")).hexdigest()
    notice = (
        "<!-- Generated by scripts/build_cs_app.py from src/cs_app.src.html; "
        f"source SHA-256: {digest}. Edit the source, then rebuild. -->\n"
    )
    return notice + source


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the artifact is stale")
    args = parser.parse_args()
    built = render(SRC.read_text(encoding="utf-8")).encode("utf-8")
    if args.check:
        if not OUT.exists() or OUT.read_bytes() != built:
            print("CS artifact is stale; run python scripts/build_cs_app.py")
            return 1
        print("CS artifact matches its source")
        return 0
    OUT.write_bytes(built)
    print(f"Built {OUT.relative_to(ROOT)} ({len(built):,} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
